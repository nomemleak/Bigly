package app.bigly.ui.display

import androidx.compose.runtime.Composable
import androidx.compose.runtime.LaunchedEffect
import androidx.compose.runtime.State
import androidx.compose.runtime.mutableFloatStateOf
import androidx.compose.runtime.remember
import androidx.compose.runtime.withFrameNanos

/**
 * Seconds elapsed while [running], advanced once per frame. Pausing keeps the
 * current value, so animations resume where they stopped.
 *
 * Read the value inside draw or layer blocks: only that phase is redone each frame.
 */
@Composable
fun rememberAnimationClock(running: Boolean): State<Float> {
    val seconds = remember { mutableFloatStateOf(0f) }
    LaunchedEffect(running) {
        if (!running) return@LaunchedEffect
        val base = seconds.floatValue
        val start = withFrameNanos { it }
        while (true) {
            withFrameNanos { now -> seconds.floatValue = base + (now - start) / 1_000_000_000f }
        }
    }
    return seconds
}
